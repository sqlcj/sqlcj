package org.sqlcj.generator;

import org.sqlcj.analysis.QueryColumn;
import org.sqlcj.analysis.QueryGroupModel;
import org.sqlcj.analysis.QueryModel;
import org.sqlcj.analysis.QueryParameter;
import org.sqlcj.schema.ColumnType;
import org.sqlcj.schema.EnumType;

import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.Set;
import java.util.function.Function;
import java.util.stream.Collectors;

public final class JavaCodeGenerator implements CodeGenerator {

    private static final String DEFAULT_PACKAGE = "generated";

    /**
     * The subpackage of the configured package every generated repository is
     * written to. No file is written into the configured package itself, so
     * each kind of generated file keeps a directory of its own.
     */
    private static final String REPOSITORY_SUBPACKAGE = "repositories";

    /** The subpackage of the configured package every row record belongs to. */
    private static final String ROW_SUBPACKAGE = "rows";

    /**
     * The subpackage of the configured package every generated enum belongs to.
     * It is named in the plural, as the other two are, because {@code enum} is
     * a Java keyword and cannot name a package.
     */
    private static final String ENUM_SUBPACKAGE = "enums";

    /**
     * The first line of every generated file, which the writer reads back to
     * tell its own output from a hand-written file at the same path.
     */
    public static final String GENERATED_NOTICE = "// Code generated by sqlcj. DO NOT EDIT.";

    /**
     * The marker every generated repository carries. A row record and a
     * generated enum are no repositories and carry no marker.
     */
    private static final String REPOSITORY_MARKER = "org.sqlcj.runtime.GeneratedRepository";

    /**
     * The mark every generated repository, row record, and enum carries, so
     * that every type it declares is non-null unless it states otherwise. A
     * nested result or parameter record is marked by its repository.
     */
    private static final String NULL_MARKED = "org.jspecify.annotations.NullMarked";

    /**
     * The annotation one nullable type carries, placed directly before the
     * simple-name segment of the type it qualifies.
     */
    static final String NULLABLE = "org.jspecify.annotations.Nullable";

    /** The runtime interface every generated repository executes through. */
    private static final String QUERY_EXECUTOR = "org.sqlcj.runtime.QueryExecutor";

    /** The runtime class one array value is bound and read through. */
    static final String SQL_ARRAY = "org.sqlcj.runtime.SqlArray";

    /** The runtime type one {@code INTERVAL} value is bound and read as. */
    static final String SQL_INTERVAL = "org.sqlcj.runtime.SqlInterval";

    static final String LIST = "java.util.List";

    static final String OBJECTS = "java.util.Objects";

    static final String STRING = "java.lang.String";

    /** Generator-owned name of the list one generated batch method takes. */
    static final String BATCH_NAME = "batch";

    /**
     * Generator-owned name of the row a generated batch method binds, which is
     * also the name of the parameter record a query with the {@code params}
     * option takes.
     */
    static final String PARAMS_NAME = JavaNames.PARAMETER_RECORD_NAME;

    /** The indentation a generated type adds to each of its members. */
    static final int MEMBER_INDENT = 4;

    /**
     * The indentation one generated method body or compact constructor gives
     * each of its statements.
     */
    static final int BODY_INDENT = 4;

    /**
     * The indentation one wrapped statement gives each of its arguments, which
     * is one call continuation past the line that opens the call.
     */
    static final int CONTINUATION_INDENT = 8;

    private final String packageName;

    /**
     * The row records of the package, keyed by row identity and ordered by the
     * group that first returned them.
     */
    private final Map<String, SharedRow> rows = new LinkedHashMap<>();

    /** The rows of the package, keyed by the lower-case row type name. */
    private final Map<String, SharedRow> rowsByPortabilityKey = new LinkedHashMap<>();

    /**
     * The enum types the package generates, keyed by enum identity and ordered
     * by the group that first used them.
     */
    private final Map<String, SharedEnum> enums = new LinkedHashMap<>();

    /** The enum types of the package, keyed by the lower-case enum type name. */
    private final Map<String, SharedEnum> enumsByPortabilityKey = new LinkedHashMap<>();

    /**
     * Every other type the package generates — repositories, row records, and
     * nested result records — keyed by its lower-case name, so that an enum
     * type cannot take a name one of them already generated.
     */
    private final Map<String, String> generatedTypesByPortabilityKey = new LinkedHashMap<>();

    /** Generates the Java enum of each enum type the package records. */
    final EnumSourceGenerator enumSourceGenerator = new EnumSourceGenerator(this);

    /** Writes the documentation of every generated type and method. */
    final JavadocGenerator javadocGenerator = new JavadocGenerator(this);

    /** Generates the result, row, and parameter records and their builders. */
    final RecordGenerator recordGenerator = new RecordGenerator(this);

    /** Generates the method of each query, its SQL, and the arguments it binds. */
    final RepositoryMethodGenerator repositoryMethodGenerator = new RepositoryMethodGenerator(this);

    /** Generates the row mappers one repository reads its results with. */
    final RowMapperGenerator rowMapperGenerator = new RowMapperGenerator(this);

    /** The helpers the generated-source classes of the package share. */
    final GeneratorSupport support = new GeneratorSupport(this);

    public JavaCodeGenerator() {
        this(DEFAULT_PACKAGE);
    }

    public JavaCodeGenerator(String packageName) {
        this.packageName = packageName;
    }

    /**
     * Generates one repository holding every method of the group, in query
     * order, with one executor field and one constructor, and records the row
     * records the group returns.
     */
    @Override
    public GeneratedFile generate(QueryGroupModel group) {
        JavaNames names = JavaNames.of(group);

        recordRows(group, names);
        recordGeneratedTypes(group, names);
        recordEnums(group);

        return new GeneratedFile(
            buildPath(names),
            generateSource(group, names)
        );
    }

    @Override
    public List<GeneratedFile> generateRows() {
        return rows.values().stream()
            .map(this::generateRowFile)
            .toList();
    }

    @Override
    public List<GeneratedFile> generateEnums() {
        return enums.values().stream()
            .map(this::generateEnumFile)
            .toList();
    }

    /**
     * Records the row records of one group, rejecting a row that conflicts with
     * a row an earlier group of the package already generated.
     */
    private void recordRows(QueryGroupModel group, JavaNames names) {
        for (JavaNames.RowNames row : names.rows()) {
            recordRow(
                new SharedRow(
                    group.name(),
                    row.tableName(),
                    row.typeName(),
                    row.columns(),
                    row.componentNames()
                )
            );
        }
    }

    /**
     * Records one row record of the package. A row of a table already recorded
     * under the same row type is the same record, so its columns must be the
     * ones the earlier group defined; a row type equal ignoring case to the row
     * type of another table is rejected, because the compiled class files of
     * those types are one path on a case-insensitive filesystem.
     */
    private void recordRow(SharedRow row) {
        SharedRow recorded = rows.get(row.identity());

        if (recorded != null) {
            if (!recorded.columns().equals(row.columns())) {
                throw new IllegalArgumentException(
                    "Table '%s' differs from its definition in query group '%s', which generates the same row type %s"
                        .formatted(
                            row.tableName(),
                            recorded.groupName(),
                            row.typeName()
                        )
                );
            }

            return;
        }

        SharedRow previous = rowsByPortabilityKey.get(row.portabilityKey());

        if (previous != null) {
            throw new IllegalArgumentException(
                "Tables '%s' and '%s' generate row types that are equal ignoring case: %s and %s"
                    .formatted(
                        previous.tableName(),
                        row.tableName(),
                        previous.typeName(),
                        row.typeName()
                    )
            );
        }

        rows.put(row.identity(), row);
        rowsByPortabilityKey.put(row.portabilityKey(), row);
    }

    /**
     * Records the types one group generates beside its enums: its repository,
     * the row records it returns, the record of each parameter group its
     * queries use, the builder its parameter records nest, the nested result
     * records of its other queries, and the nested parameter record of each
     * query that has one.
     */
    private void recordGeneratedTypes(QueryGroupModel group, JavaNames names) {
        recordGeneratedType(names.repositoryClassName());

        for (JavaNames.RowNames row : names.rows()) {
            recordGeneratedType(row.typeName());
        }

        for (JavaNames.GroupNames parameterGroup : names.groups()) {
            recordGeneratedType(parameterGroup.typeName());
        }

        if (hasBuilder(group, names)) {
            recordGeneratedType(JavaNames.BUILDER_TYPE_NAME);
        }

        for (int index = 0; index < group.queries().size(); index++) {
            QueryModel query = group.queries().get(index);

            if (support.hasResultType(query) && !support.returnsSharedRow(query) && !support.returnsValue(query)) {
                recordGeneratedType(names.queries().get(index).resultTypeName());
            }

            if (support.hasParamsRecord(query)) {
                recordGeneratedType(names.queries().get(index).paramsTypeName());
            }
        }
    }

    /**
     * Whether one repository declares the builder its parameter records nest,
     * which is one name however many records nest it: every parameter group's
     * record has one, and so has every {@code Params} record with a component.
     */
    private boolean hasBuilder(QueryGroupModel group, JavaNames names) {
        return !names.groups().isEmpty()
            || group.queries().stream().anyMatch(support::hasParamsBuilder);
    }

    /**
     * Records one generated type of the package, rejecting a type whose name is
     * equal ignoring case to an enum type an earlier group already generated,
     * because the compiled class files of those types are one path on a
     * case-insensitive filesystem.
     */
    private void recordGeneratedType(String typeName) {
        String portabilityKey = typeName.toLowerCase(Locale.ROOT);
        SharedEnum generatedEnum = enumsByPortabilityKey.get(portabilityKey);

        if (generatedEnum != null) {
            throw enumTypeCollision(generatedEnum, typeName);
        }

        generatedTypesByPortabilityKey.putIfAbsent(portabilityKey, typeName);
    }

    /**
     * Records the enum types one group uses, in the order its columns and
     * parameters first name them, an embedded row's own columns included.
     */
    private void recordEnums(QueryGroupModel group) {
        for (QueryModel query : group.queries()) {
            for (QueryColumn column : readColumns(query.columns())) {
                if (column.type() == ColumnType.ENUM) {
                    recordEnum(group, column.enumType());
                }
            }

            for (QueryParameter parameter : query.parameters()) {
                if (parameter.type() == ColumnType.ENUM) {
                    recordEnum(group, parameter.enumType());
                }
            }
        }
    }

    private void recordEnum(QueryGroupModel group, String enumName) {
        EnumType declared = group.enums().stream()
            .filter(candidate -> candidate.name().equalsIgnoreCase(enumName))
            .findFirst()
            .orElseThrow(
                () -> new IllegalStateException("Enum type not found in schema: " + enumName)
            );

        recordEnum(
            new SharedEnum(
                group.name(),
                declared.name(),
                JavaNames.enumTypeName(declared.name()),
                declared.labels(),
                JavaNames.enumConstantNames(declared.name(), declared.labels())
            )
        );
    }

    /**
     * Records one enum type of the package. An enum already recorded under the
     * same enum type is the same Java enum, so its labels must be the ones the
     * earlier group defined; an enum type equal ignoring case to another enum
     * or to another generated type is rejected, because the compiled class
     * files of those types are one path on a case-insensitive filesystem.
     */
    private void recordEnum(SharedEnum sharedEnum) {
        SharedEnum recorded = enums.get(sharedEnum.identity());

        if (recorded != null) {
            if (!recorded.labels().equals(sharedEnum.labels())) {
                throw new IllegalArgumentException(
                    "Enum type '%s' differs from its definition in query group '%s', which generates the same enum type %s"
                        .formatted(
                            sharedEnum.enumName(),
                            recorded.groupName(),
                            sharedEnum.typeName()
                        )
                );
            }

            return;
        }

        SharedEnum previous = enumsByPortabilityKey.get(sharedEnum.portabilityKey());

        if (previous != null) {
            throw new IllegalArgumentException(
                "Enum types '%s' and '%s' generate enum types that are equal ignoring case: %s and %s"
                    .formatted(
                        previous.enumName(),
                        sharedEnum.enumName(),
                        previous.typeName(),
                        sharedEnum.typeName()
                    )
            );
        }

        String generatedType = generatedTypesByPortabilityKey.get(sharedEnum.portabilityKey());

        if (generatedType != null) {
            throw enumTypeCollision(sharedEnum, generatedType);
        }

        enums.put(sharedEnum.identity(), sharedEnum);
        enumsByPortabilityKey.put(sharedEnum.portabilityKey(), sharedEnum);
    }

    private IllegalArgumentException enumTypeCollision(SharedEnum sharedEnum, String typeName) {
        return new IllegalArgumentException(
            "Enum type '%s' generates %s, which is equal ignoring case to the generated type %s"
                .formatted(
                    sharedEnum.enumName(),
                    sharedEnum.typeName(),
                    typeName
                )
        );
    }

    private Path buildPath(JavaNames names) {
        return packageDirectory(REPOSITORY_SUBPACKAGE)
            .resolve(names.repositoryClassName() + ".java");
    }

    /** The directory, relative to the output root, one subpackage is written to. */
    private Path packageDirectory(String subpackage) {
        String[] segments = subpackageName(subpackage).split("\\.");

        return Path.of(
            segments[0],
            Arrays.copyOfRange(segments, 1, segments.length)
        );
    }

    /** The package one kind of generated file belongs to. */
    private String subpackageName(String subpackage) {
        return packageName + "." + subpackage;
    }

    /**
     * Renders one generated file twice over a scope of its own, so that every
     * name it writes is resolved against the types it declares and the
     * generated types it names, and so that a line is measured as it is
     * written. The imports are the types the second pass wrote by their simple
     * name.
     */
    private String generateFile(
        String subpackage,
        Set<String> declaredNames,
        Set<String> packageTypeNames,
        Function<NameScope, String> declaration
    ) {
        NameScope collecting = NameScope.collecting(
            Set.of(subpackageName(ROW_SUBPACKAGE), subpackageName(ENUM_SUBPACKAGE)),
            declaredNames,
            packageTypeNames
        );

        declaration.apply(collecting);

        NameScope scope = collecting.resolved();
        String declarationText = declaration.apply(scope);

        List<String> sections = new ArrayList<>();

        sections.add(GENERATED_NOTICE);
        sections.add(generatePackage(subpackage));

        String imports = scope.imports();

        if (!imports.isEmpty()) {
            sections.add(imports);
        }

        sections.add(declarationText);

        return String.join("\n\n", sections);
    }

    /**
     * Generates the source of one repository, which ends in the one blank line
     * every repository has ended in since the first generated file was
     * written.
     */
    private String generateSource(QueryGroupModel group, JavaNames names) {
        return generateFile(
            REPOSITORY_SUBPACKAGE,
            repositoryDeclaredNames(group, names),
            Set.of(),
            scope -> generateDeclaration(
                javadocGenerator.generateRepositoryJavaDoc(group),
                scope.annotation(REPOSITORY_MARKER)
                    + "\n"
                    + scope.annotation(NULL_MARKED)
                    + "\n"
                    + generateClass(group, names, scope)
            )
        ) + "\n";
    }

    /**
     * The simple names one repository's file declares: the repository, the
     * result, parameter, and parameter group records nested in it, and the
     * builder its parameter records nest, which is one name however many of
     * them nest it. A query returning one complete table row names the
     * package's row record, which another file declares.
     */
    private Set<String> repositoryDeclaredNames(QueryGroupModel group, JavaNames names) {
        Set<String> declaredNames = new LinkedHashSet<>();

        declaredNames.add(names.repositoryClassName());

        if (hasBuilder(group, names)) {
            declaredNames.add(JavaNames.BUILDER_TYPE_NAME);
        }

        for (JavaNames.GroupNames parameterGroup : names.groups()) {
            declaredNames.add(parameterGroup.typeName());
        }

        for (int index = 0; index < group.queries().size(); index++) {
            QueryModel query = group.queries().get(index);

            if (support.hasResultType(query) && !support.returnsSharedRow(query) && !support.returnsValue(query)) {
                declaredNames.add(names.queries().get(index).resultTypeName());
            }

            if (support.hasParamsRecord(query)) {
                declaredNames.add(names.queries().get(index).paramsTypeName());
            }
        }

        return declaredNames;
    }

    /**
     * Writes the Javadoc of one generated type directly above the declaration
     * it documents, as hand-written Java does.
     */
    private String generateDeclaration(String javaDoc, String declaration) {
        return javaDoc.stripTrailing() + "\n" + declaration;
    }

    /** Generates the file of one row record of the package. */
    private GeneratedFile generateRowFile(SharedRow row) {
        return new GeneratedFile(
            packageDirectory(ROW_SUBPACKAGE).resolve(row.typeName() + ".java"),
            generateRowSource(row)
        );
    }

    private String generateRowSource(SharedRow row) {
        return generateFile(
            ROW_SUBPACKAGE,
            Set.of(row.typeName()),
            Set.of(),
            scope -> generateDeclaration(
                javadocGenerator.generateRowJavaDoc(row),
                scope.annotation(NULL_MARKED) + "\n" + recordGenerator.generateRecord(
                    row.typeName(),
                    row.columns(),
                    row.componentNames(),
                    scope
                )
            )
        );
    }

    /** Generates the file of one Java enum of the package. */
    private GeneratedFile generateEnumFile(SharedEnum sharedEnum) {
        return new GeneratedFile(
            packageDirectory(ENUM_SUBPACKAGE).resolve(sharedEnum.typeName() + ".java"),
            generateEnumSource(sharedEnum)
        );
    }

    /**
     * Generates the source of one Java enum. The enum subpackage holds every
     * generated enum of the run, so each of their names shadows the
     * {@code java.lang} type it is equal to in this file as well, which is why
     * the scope is given them all.
     */
    private String generateEnumSource(SharedEnum sharedEnum) {
        return generateFile(
            ENUM_SUBPACKAGE,
            Set.of(sharedEnum.typeName()),
            enums.values().stream()
                .map(SharedEnum::typeName)
                .collect(Collectors.toCollection(LinkedHashSet::new)),
            scope -> generateDeclaration(
                javadocGenerator.generateEnumJavaDoc(sharedEnum),
                scope.annotation(NULL_MARKED) + "\n" + enumSourceGenerator.generateEnum(sharedEnum, scope)
            )
        );
    }

    /** The fully qualified name of the Java enum one enum type generates. */
    String enumTypeQualifiedName(String enumType) {
        return subpackageName(ENUM_SUBPACKAGE) + "." + JavaNames.enumTypeName(enumType);
    }

    /** The fully qualified name of one generated row record. */
    String rowTypeQualifiedName(String rowTypeName) {
        return subpackageName(ROW_SUBPACKAGE) + "." + rowTypeName;
    }

    private String generatePackage(String subpackage) {
        return "package " + subpackageName(subpackage) + ";";
    }

    /**
     * The columns one result reads from the result set, in read order, which
     * are the own columns of an embedded row in place of the component that
     * holds it.
     */
    private List<QueryColumn> readColumns(List<QueryColumn> columns) {
        List<QueryColumn> read = new ArrayList<>();

        for (QueryColumn column : columns) {
            if (column.row()) {
                read.addAll(column.rowColumns());

                continue;
            }

            read.add(column);
        }

        return read;
    }

    private String generateClass(QueryGroupModel group, JavaNames names, NameScope scope) {
        List<String> members = new ArrayList<>();

        members.add(generateExecutorField(scope));
        members.add(generateConstructor(names, scope));

        for (JavaNames.RowNames row : names.rows()) {
            if (row.returnedWhole()) {
                members.add(
                    rowMapperGenerator.generateRowMapper(
                        scope.type(rowTypeQualifiedName(row.typeName())),
                        row.mapperName(),
                        row.columns(),
                        scope
                    )
                );
            }
        }

        Set<String> writtenGroups = new LinkedHashSet<>();

        for (int index = 0; index < group.queries().size(); index++) {
            QueryModel query = group.queries().get(index);
            JavaNames.QueryNames queryNames = names.queries().get(index);

            for (JavaNames.MethodParameter parameter : queryNames.methodParameters()) {
                if (
                    parameter.group() != null
                        && writtenGroups.add(parameter.group().groupName())
                ) {
                    members.add(
                        javadocGenerator.generateGroupRecordJavaDoc(parameter.group(), query)
                            + recordGenerator.generateParameterRecord(
                                recordGenerator.groupRecord(parameter.group(), names.repositoryClassName()),
                                scope
                            )
                    );
                }
            }

            if (support.hasResultType(query) && !support.returnsSharedRow(query) && !support.returnsValue(query)) {
                members.add(
                    javadocGenerator.generateResultRecordJavaDoc(query, queryNames)
                        + recordGenerator.generateRecord(
                            queryNames.resultTypeName(),
                            query.columns(),
                            queryNames.componentNames(),
                            scope
                        )
                );
            }

            if (support.hasParamsRecord(query)) {
                members.add(
                    javadocGenerator.generateParamsRecordJavaDoc(query, queryNames)
                        + recordGenerator.generateParamsRecord(
                            query,
                            names.repositoryClassName(),
                            queryNames,
                            scope
                        )
                );
            }

            if (support.returnsValue(query)) {
                members.add(
                    rowMapperGenerator.generateValueRowMapper(query, queryNames.rowMapperName(), scope)
                );
            } else if (support.hasResult(query) && !support.returnsSharedRow(query)) {
                members.add(
                    rowMapperGenerator.generateRowMapper(
                        queryNames.resultTypeName(),
                        queryNames.rowMapperName(),
                        query.columns(),
                        scope
                    )
                );
            }

            members.add(
                javadocGenerator.generateJavaDoc(query, group.queriesPath(), queryNames, scope)
                    + repositoryMethodGenerator.generateMethod(query, names.repositoryClassName(), queryNames, scope)
            );
        }

        return """
            public final class %s {

            %s
            }
            """
            .formatted(
                names.repositoryClassName(),
                members.stream()
                    .filter(member -> !member.isBlank())
                    .map(support::indent)
                    .collect(Collectors.joining("\n\n"))
            );
    }

    private String generateExecutorField(NameScope scope) {
        return """
            private final %s executor;
            """
            .formatted(scope.type(QUERY_EXECUTOR));
    }

    private String generateConstructor(JavaNames names, NameScope scope) {
        return """
            public %s(%s executor) {
                this.executor = executor;
            }
            """
            .formatted(names.repositoryClassName(), scope.type(QUERY_EXECUTOR));
    }

}
