package org.sqlcj.generator;

import org.sqlcj.analysis.QueryColumn;
import org.sqlcj.analysis.QueryGroupModel;
import org.sqlcj.analysis.QueryModel;
import org.sqlcj.parser.QueryType;

import java.util.ArrayList;
import java.util.List;
import java.util.stream.IntStream;

/**
 * Writes the documentation of every generated type and method: the comment of
 * one repository, row record, and generated enum, the comment of one query
 * method with the tags of its parameters, its result, and its cardinality
 * failure, the comment of one nested record with one tag per component, and the
 * escaping that keeps written text the text it is written as. It reads the
 * generator it belongs to for the helpers the generated source shares.
 */
final class JavadocGenerator {

    /**
     * The runtime failure a {@code :one} or {@code :optional} method raises for
     * a row count its cardinality does not allow, which only their documented
     * {@code @throws} tags name.
     */
    private static final String QUERY_CARDINALITY_EXCEPTION = "org.sqlcj.runtime.QueryCardinalityException";

    /**
     * The indentation the continuation lines of one documentation tag carry
     * past the {@code * } of their line, so that a tag whose text does not fit
     * one line reads as one tag.
     */
    private static final int TAG_CONTINUATION_INDENT = 8;

    /** The generator these generated sources belong to. */
    private final JavaCodeGenerator generator;

    JavadocGenerator(JavaCodeGenerator generator) {
        this.generator = generator;
    }

    String generateEnumJavaDoc(SharedEnum sharedEnum) {
        return """
            /**
             * Generated by sqlcj.
             *
             * <p>Enum: %s
             */
            """
            .formatted(escapeJavadoc(sharedEnum.enumName()));
    }

    /**
     * The documentation of one shared row record, which keeps the text every
     * row record has carried and names the result column each of its components
     * reads.
     */
    String generateRowJavaDoc(SharedRow row) {
        return generateDocComment(
            List.of(
                "Generated by sqlcj.",
                "",
                "<p>Table: " + escapeJavadoc(row.tableName())
            ),
            generateComponentTags(row.componentNames(), describeResultComponents(row.columns()))
        );
    }

    String generateRepositoryJavaDoc(QueryGroupModel group) {
        return """
            /**
             * Generated by sqlcj.
             *
             * <p>Repository: %s
             */
            """
            .formatted(escapeJavadoc(group.name()));
    }

    /**
     * The documentation of one generated query method: the query's own comment
     * lines, if it has any, its SQL as the query source writes it, where it is
     * defined, which is left out when the group's query source is unknown, and
     * the tags of its parameters, its result, and its cardinality failure.
     * Every part is escaped, so that no written text can end the comment, start
     * a Javadoc tag, or be read as a Unicode escape.
     */
    String generateJavaDoc(
        QueryModel query,
        String queriesPath,
        JavaNames.QueryNames names,
        NameScope scope
    ) {
        List<String> description = new ArrayList<>();

        for (String comment : query.comment()) {
            description.add(escapeJavadoc(comment));
        }

        if (!query.comment().isEmpty()) {
            description.add("");
        }

        description.add("<pre>");

        for (String sqlLine : query.writtenSql().lines().toList()) {
            description.add(escapeJavadoc(sqlLine));
        }

        description.add("</pre>");

        if (queriesPath != null) {
            description.add("");
            description.add(
                "<p>Defined at <code>%s:%d</code>."
                    .formatted(escapeJavadoc(queriesPath), query.line())
            );
        }

        return generateDocComment(description, generateMethodTags(query, names, scope));
    }

    /**
     * Writes one documentation comment: its description lines, and its tags
     * after one blank comment line where it carries any.
     */
    private String generateDocComment(List<String> description, List<String> tags) {
        List<String> lines = new ArrayList<>();

        description.stream()
            .map(this::javaDocLine)
            .forEach(lines::add);

        if (!tags.isEmpty()) {
            lines.add(javaDocLine(""));
            lines.addAll(tags);
        }

        return "/**\n" + String.join("\n", lines) + "\n */\n";
    }

    /** One line of a method's documentation, carrying its escaped text. */
    private String javaDocLine(String text) {
        return (" * " + text).stripTrailing();
    }

    /**
     * One continuation line of a documentation tag, indented past the tag it
     * continues so that the two read as one tag.
     */
    private String continuedTagLine(String text) {
        return javaDocLine(" ".repeat(TAG_CONTINUATION_INDENT) + text);
    }

    /**
     * Writes one documentation tag within the column limit: on one line where
     * it fits, and otherwise broken at a space, each continuation line indented
     * past the tag it continues. The break never falls inside a
     * {@code <code>} element, because no text one holds carries a space. A word
     * that alone passes the limit stays on its line, as every other generated
     * line that cannot be broken further does.
     *
     * <p>Every tag is measured where a member of a generated type is written,
     * which is where a method's and a nested record's tags stand, so that one
     * limit decides the break wherever the comment is written.
     */
    private List<String> generateTagLines(String tag) {
        List<String> lines = new ArrayList<>();
        StringBuilder line = new StringBuilder();

        for (String word : tag.split(" ")) {
            if (line.isEmpty()) {
                line.append(word);

                continue;
            }

            if (generator.support.fits(0, javaDocLine(line + " " + word))) {
                line.append(" ").append(word);

                continue;
            }

            lines.add(javaDocLine(line.toString()));
            line.setLength(0);
            line.append(" ".repeat(TAG_CONTINUATION_INDENT)).append(word);
        }

        lines.add(javaDocLine(line.toString()));

        return lines;
    }

    /** Writes one name or placeholder as the code text it is. */
    private String javaDocCode(String text) {
        return "<code>" + escapeJavadoc(text) + "</code>";
    }

    /**
     * The tags of one generated method, in the order javadoc renders them: one
     * {@code @param} per method parameter, in the order the method takes them,
     * the {@code @return} of every type that returns a result, and the
     * {@code @throws} of a cardinality the executor enforces.
     */
    private List<String> generateMethodTags(
        QueryModel query,
        JavaNames.QueryNames names,
        NameScope scope
    ) {
        List<String> tags = new ArrayList<>();

        for (String tag : generateParameterTags(query, names)) {
            tags.addAll(generateTagLines(tag));
        }

        for (String tag : generateReturnTags(query)) {
            tags.addAll(generateTagLines(tag));
        }

        tags.addAll(generateThrowsTags(query, scope));

        return tags;
    }

    /**
     * The {@code @param} tag of each parameter one generated method takes: the
     * placeholder a plain parameter binds, the placeholders of the group a
     * group record holds, the whole parameter list of a query with the
     * {@code params} option, and the executions of one batch.
     */
    private List<String> generateParameterTags(QueryModel query, JavaNames.QueryNames names) {
        if (generator.support.isBatchExec(query)) {
            return List.of(
                "@param %s the parameters of each execution, run in the order of the list"
                    .formatted(JavaCodeGenerator.BATCH_NAME)
            );
        }

        if (query.parameterRecord()) {
            return List.of(
                "@param %s the values of every placeholder of the query, one component each"
                    .formatted(JavaCodeGenerator.PARAMS_NAME)
            );
        }

        return names.methodParameters().stream()
            .map(
                methodParameter -> "@param %s %s"
                    .formatted(
                        methodParameter.name(),
                        methodParameter.group() == null
                            ? describeValues(
                                List.of(query.placeholders().get(methodParameter.parameter()))
                            )
                            : describeValues(
                                groupPlaceholders(query, methodParameter.group().groupName())
                            )
                    )
            )
            .toList();
    }

    /**
     * The placeholders of one parameter group that one query writes, in logical
     * parameter order, which for the query that defines the group's record are
     * that record's components in component order.
     */
    private List<String> groupPlaceholders(QueryModel query, String groupName) {
        return IntStream.range(0, query.parameters().size())
            .filter(index -> groupName.equals(query.parameters().get(index).group()))
            .mapToObj(index -> query.placeholders().get(index))
            .toList();
    }

    /**
     * Names the values one method parameter or record component binds, which is
     * one placeholder for a plain parameter and every placeholder of the group
     * for a group record. Three or more are listed with a final {@code and}.
     */
    private String describeValues(List<String> placeholders) {
        if (placeholders.size() == 1) {
            return "the value of " + javaDocCode(placeholders.get(0));
        }

        List<String> codes = placeholders.stream()
            .map(this::javaDocCode)
            .toList();

        return "the values of "
            + (codes.size() == 2
                ? codes.get(0) + " and " + codes.get(1)
                : String.join(", ", codes.subList(0, codes.size() - 1))
                    + ", and "
                    + codes.get(codes.size() - 1));
    }

    /**
     * The {@code @return} tag of one generated method, which states what the
     * executor returns for each number of rows the query matches. A query type
     * that analysis rejects carries no tag, because no configuration reaches
     * its method.
     */
    private List<String> generateReturnTags(QueryModel query) {
        return switch (query.type()) {
            case ONE -> List.of("@return " + describeResult(query, "the one row the query returns"));
            case OPTIONAL -> List.of(
                "@return "
                    + describeResult(
                        query,
                        "the row the query returns, or empty when it returns none"
                    )
            );
            case MANY -> List.of(
                "@return "
                    + describeResult(
                        query,
                        "every row the query returns, in the order the database returns them, "
                            + "or an empty list"
                    )
            );
            case EXEC -> List.of("@return the number of rows the statement affected");
            case BATCH_EXEC -> List.of(
                "@return the count the driver reports for each element of %s, in the order of the list"
                    .formatted(javaDocCode(JavaCodeGenerator.BATCH_NAME))
            );
            case EXEC_RESULT, BATCH_MANY, BATCH_ONE -> List.of();
        };
    }

    /**
     * What one generated method returns of each row the query matches, which is
     * the row itself and, for a query of one non-null column, that column's
     * value.
     */
    private String describeResult(QueryModel query, String rows) {
        return generator.support.returnsValue(query)
            ? "the %s value of %s".formatted(javaDocCode(query.columns().get(0).name()), rows)
            : rows;
    }

    /**
     * The {@code @throws} tag of one generated method, which a {@code :one} and
     * an {@code :optional} query carry for the row counts the executor refuses,
     * each naming the Spring exception the Spring Boot starter raises in its
     * place, as plain text so that the comment is valid without Spring on the
     * class path.
     *
     * <p>The tag's own text passes one line, so it continues on the lines
     * written here, each already within the column limit.
     */
    private List<String> generateThrowsTags(QueryModel query, NameScope scope) {
        if (query.type() == QueryType.ONE) {
            return List.of(
                javaDocLine(
                    "@throws %s if the query returns no row or more than one;"
                        .formatted(scope.type(QUERY_CARDINALITY_EXCEPTION))
                ),
                continuedTagLine(
                    "the Spring Boot starter raises Spring's <code>EmptyResultDataAccessException</code>"
                ),
                continuedTagLine(
                    "for no row and <code>IncorrectResultSizeDataAccessException</code> for several in its place"
                )
            );
        }

        if (generator.support.isOptional(query)) {
            return List.of(
                javaDocLine(
                    "@throws %s if the query returns more than one row;"
                        .formatted(scope.type(QUERY_CARDINALITY_EXCEPTION))
                ),
                continuedTagLine(
                    "the Spring Boot starter raises Spring's "
                        + "<code>IncorrectResultSizeDataAccessException</code> in its place"
                )
            );
        }

        return List.of();
    }

    /**
     * The documentation of one record built from a query's result: a
     * description naming the method that returns it and one {@code @param} per
     * component.
     */
    String generateResultRecordJavaDoc(QueryModel query, JavaNames.QueryNames names) {
        return generateDocComment(
            List.of("A row that %s returns.".formatted(javaDocCode(names.methodName()))),
            generateComponentTags(
                names.componentNames(),
                describeResultComponents(query.columns())
            )
        );
    }

    /**
     * The documentation of the parameter record of one query: a description
     * naming the method it belongs to, which a batch method takes one of per
     * execution, and one {@code @param} per placeholder it holds. A query that
     * binds no parameter has no component to document.
     */
    String generateParamsRecordJavaDoc(QueryModel query, JavaNames.QueryNames names) {
        return generateDocComment(
            List.of(
                (generator.support.isBatchExec(query)
                    ? "The parameters of one execution of %s."
                    : "The parameters of %s.")
                    .formatted(javaDocCode(names.methodName()))
            ),
            generateComponentTags(names.parameterNames(), describeBoundComponents(query.placeholders()))
        );
    }

    /**
     * The documentation of one parameter group's record, whose components are
     * the placeholders the query that defines the record writes for the group.
     */
    String generateGroupRecordJavaDoc(JavaNames.GroupNames group, QueryModel query) {
        return generateDocComment(
            List.of(
                "The values of the %s parameter group.".formatted(javaDocCode(group.groupName()))
            ),
            generateComponentTags(
                group.componentNames(),
                describeBoundComponents(groupPlaceholders(query, group.groupName()))
            )
        );
    }

    /** What each component of one result record reads. */
    private List<String> describeResultComponents(List<QueryColumn> columns) {
        return columns.stream()
            .map(
                column -> column.row()
                    ? "the row of " + javaDocCode(column.name())
                    : "the %s column".formatted(javaDocCode(column.name()))
            )
            .toList();
    }

    /** What each component of one record built from parameters binds. */
    private List<String> describeBoundComponents(List<String> placeholders) {
        return placeholders.stream()
            .map(placeholder -> describeValues(List.of(placeholder)))
            .toList();
    }

    /** One {@code @param} tag per component of one generated record. */
    private List<String> generateComponentTags(
        List<String> componentNames,
        List<String> descriptions
    ) {
        return IntStream.range(0, componentNames.size())
            .mapToObj(
                index -> "@param %s %s"
                    .formatted(componentNames.get(index), descriptions.get(index))
            )
            .flatMap(tag -> generateTagLines(tag).stream())
            .toList();
    }

    /**
     * Escapes a value rendered inside a generated Javadoc block, so that it is
     * read as the text it is written as: {@code &} first, so that the entities
     * this writes are not escaped again, then {@code <} and {@code >}, which
     * would open an HTML element, {@code @}, which would start a Javadoc tag,
     * {@code \}, which javac reads as a Unicode escape anywhere in a source
     * file, and {@code *}{@code /}, which would end the comment. A brace is
     * written as it stands, because an inline tag starts with a brace followed
     * by an {@code @}, which this escapes.
     */
    private String escapeJavadoc(String value) {
        return value
            .replace("&", "&amp;")
            .replace("<", "&lt;")
            .replace(">", "&gt;")
            .replace("@", "&#64;")
            .replace("\\", "&#92;")
            .replace("*/", "*&#47;");
    }
}
