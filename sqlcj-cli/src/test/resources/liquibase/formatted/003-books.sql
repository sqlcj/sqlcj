CREATE TABLE books
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id    BIGINT      NOT NULL CONSTRAINT fk_books_author REFERENCES authors (id),
    title        TEXT        NOT NULL,
    format       book_format NOT NULL DEFAULT 'paperback',
    price        NUMERIC(10, 2),
    published_at TIMESTAMPTZ
);

CREATE INDEX ix_books_author ON books (author_id);
