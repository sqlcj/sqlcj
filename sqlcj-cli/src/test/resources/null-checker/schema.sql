-- A sqlcj-owned fixture that reads every mapped type, scalar and array,
-- nullable and NOT NULL, through every result shape a generated repository
-- has. It is generated and compiled under a null checker; no database runs
-- it.

CREATE TYPE mood AS ENUM ('happy', 'sad');

CREATE TABLE sensors
(
    id    BIGSERIAL PRIMARY KEY,
    name  TEXT NOT NULL,
    note  TEXT
);

CREATE TABLE readings
(
    id                     BIGSERIAL PRIMARY KEY,
    sensor_id              BIGINT NOT NULL,
    owner_id               BIGINT,
    nn_integer             INTEGER NOT NULL,
    null_integer           INTEGER,
    nn_bigint              BIGINT NOT NULL,
    null_bigint            BIGINT,
    nn_smallint            SMALLINT NOT NULL,
    null_smallint          SMALLINT,
    nn_boolean             BOOLEAN NOT NULL,
    null_boolean           BOOLEAN,
    nn_varchar             VARCHAR(255) NOT NULL,
    null_varchar           VARCHAR(255),
    nn_text                TEXT NOT NULL,
    null_text              TEXT,
    nn_date                DATE NOT NULL,
    null_date              DATE,
    nn_time                TIME NOT NULL,
    null_time              TIME,
    nn_timestamp           TIMESTAMP NOT NULL,
    null_timestamp         TIMESTAMP,
    nn_timestamptz         TIMESTAMPTZ NOT NULL,
    null_timestamptz       TIMESTAMPTZ,
    nn_numeric             NUMERIC(10, 2) NOT NULL,
    null_numeric           NUMERIC(10, 2),
    nn_real                REAL NOT NULL,
    null_real              REAL,
    nn_double              DOUBLE PRECISION NOT NULL,
    null_double            DOUBLE PRECISION,
    nn_uuid                UUID NOT NULL,
    null_uuid              UUID,
    nn_bytea               BYTEA NOT NULL,
    null_bytea             BYTEA,
    nn_json                JSON NOT NULL,
    null_json              JSON,
    nn_jsonb               JSONB NOT NULL,
    null_jsonb             JSONB,
    nn_citext              citext NOT NULL,
    null_citext            citext,
    nn_inet                inet NOT NULL,
    null_inet              inet,
    nn_cidr                cidr NOT NULL,
    null_cidr              cidr,
    nn_macaddr             macaddr NOT NULL,
    null_macaddr           macaddr,
    nn_macaddr8            macaddr8 NOT NULL,
    null_macaddr8          macaddr8,
    nn_interval            INTERVAL NOT NULL,
    null_interval          INTERVAL,
    nn_mood                mood NOT NULL,
    null_mood              mood,
    nn_integer_array       INTEGER[] NOT NULL,
    null_integer_array     INTEGER[],
    nn_bigint_array        BIGINT[] NOT NULL,
    null_bigint_array      BIGINT[],
    nn_smallint_array      SMALLINT[] NOT NULL,
    null_smallint_array    SMALLINT[],
    nn_boolean_array       BOOLEAN[] NOT NULL,
    null_boolean_array     BOOLEAN[],
    nn_varchar_array       VARCHAR[] NOT NULL,
    null_varchar_array     VARCHAR[],
    nn_text_array          TEXT[] NOT NULL,
    null_text_array        TEXT[],
    nn_date_array          DATE[] NOT NULL,
    null_date_array        DATE[],
    nn_time_array          TIME[] NOT NULL,
    null_time_array        TIME[],
    nn_timestamp_array     TIMESTAMP[] NOT NULL,
    null_timestamp_array   TIMESTAMP[],
    nn_timestamptz_array   TIMESTAMPTZ[] NOT NULL,
    null_timestamptz_array TIMESTAMPTZ[],
    nn_numeric_array       NUMERIC[] NOT NULL,
    null_numeric_array     NUMERIC[],
    nn_real_array          REAL[] NOT NULL,
    null_real_array        REAL[],
    nn_double_array        DOUBLE PRECISION[] NOT NULL,
    null_double_array      DOUBLE PRECISION[],
    nn_uuid_array          UUID[] NOT NULL,
