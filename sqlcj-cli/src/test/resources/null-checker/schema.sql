    nn_macaddr8_array      macaddr8[] NOT NULL,
    null_macaddr8_array    macaddr8[],
    nn_interval_array      INTERVAL[] NOT NULL,
    null_interval_array    INTERVAL[],
    nn_mood_array          mood[] NOT NULL,
    null_mood_array        mood[]
);
