package org.sqlcj.io;

import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import org.sqlcj.generator.JavaCodeGenerator;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.PosixFilePermissions;
import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.junit.jupiter.api.Assumptions.assumeFalse;

class GeneratedOutputManifestTest {

    /** The notice every manifest begins with, before its owner line. */
    private static final String NOTICE = """
        # Code generated by sqlcj. DO NOT EDIT.
        # sqlcj reads this file when it next generates this package: it deletes the
        # files listed below that it no longer generates, and it refuses to generate
        # this package from any configuration file other than the one named below.
        # This file is safe to delete only together with the files it lists, for
        # example with the whole output directory.
        """;

    @TempDir
    Path tempDir;

    private final GeneratedOutputManifest manifest = new GeneratedOutputManifest();

    @Test
    void shouldReadNoContentsWithoutAManifest() throws IOException {
        assertEquals(
            Optional.empty(),
            manifest.read(tempDir.resolve("generated"), "dev.example.generated")
        );
    }

    /**
     * The manifest of one package sits in that package's own directory, and a
     * manifest written before the notice existed, its owner line first, reads
     * as it always did.
     */
    @Test
    void shouldReadTheManifestOfThePackageDirectory() throws IOException {
        Path outputDirectory = tempDir.resolve("generated");

        Files.createDirectories(outputDirectory.resolve("dev/example/generated"));

        Files.writeString(
            outputDirectory.resolve("dev/example/generated/sqlcj-manifest.txt"),
            """
                # config: ../sqlcj.yaml
                dev/example/generated/repositories/OrdersRepository.java
                dev/example/generated/repositories/UsersRepository.java
                """
        );

        assertEquals(
            Optional.of(
                new GeneratedOutputManifest.Contents(
                    "../sqlcj.yaml",
                    List.of(
                        "dev/example/generated/repositories/OrdersRepository.java",
                        "dev/example/generated/repositories/UsersRepository.java"
                    )
                )
            ),
            manifest.read(outputDirectory, "dev.example.generated")
        );
    }

    /** A manifest of another package in the same output directory is not read. */
    @Test
    void shouldReadNoContentsForAnotherPackage() throws IOException {
        Path outputDirectory = tempDir.resolve("generated");

        manifest.write(
            outputDirectory,
            "dev.example.generated",
            "../sqlcj.yaml",
            List.of(Path.of("dev", "example", "generated", "UsersRepository.java"))
        );

        assertEquals(
            Optional.empty(),
            manifest.read(outputDirectory, "dev.other.generated")
        );
    }

    /**
     * The owner line and every entry stand under the notice, which says what
     * the file is, what the next run does with it, and when deleting it is
     * safe.
     */
    @Test
    void shouldWriteTheNoticeConfigurationAndSortedEntriesTerminatedByNewlines()
        throws IOException {
        Path outputDirectory = tempDir.resolve("generated");

        manifest.write(
            outputDirectory,
            "dev.example.generated",
            "../sqlcj.yaml",
            List.of(
                Path.of("dev", "example", "generated", "UsersRepository.java"),
                Path.of("dev", "example", "generated", "OrdersRepository.java")
            )
        );

        assertEquals(
            """
                # Code generated by sqlcj. DO NOT EDIT.
                # sqlcj reads this file when it next generates this package: it deletes the
                # files listed below that it no longer generates, and it refuses to generate
                # this package from any configuration file other than the one named below.
                # This file is safe to delete only together with the files it lists, for
                # example with the whole output directory.
                # config: ../sqlcj.yaml
                dev/example/generated/OrdersRepository.java
                dev/example/generated/UsersRepository.java
                """,
            Files.readString(
                outputDirectory.resolve("dev/example/generated/sqlcj-manifest.txt")
            )
        );
    }

    /**
     * The owning configuration is the first {@code # config: } line before the
     * first entry; every other line beginning {@code #} is ignored wherever it
     * stands, the notice and a later owner line included.
     */
    @Test
    void shouldReadTheOwnerLineBeforeTheFirstEntryAndIgnoreEveryOtherCommentLine()
        throws IOException {
        Path outputDirectory = tempDir.resolve("generated");

        writeManifest(
            outputDirectory,
            NOTICE
                + """
                    # config: ../sqlcj.yaml
                    # config: ../other.yaml
                    dev/example/generated/repositories/OrdersRepository.java
                    # a note a reader added
                    # config: ../later.yaml
                    dev/example/generated/repositories/UsersRepository.java
                    """
        );

        assertEquals(
            Optional.of(
                new GeneratedOutputManifest.Contents(
                    "../sqlcj.yaml",
                    List.of(
                        "dev/example/generated/repositories/OrdersRepository.java",
                        "dev/example/generated/repositories/UsersRepository.java"
                    )
                )
            ),
            manifest.read(outputDirectory, "dev.example.generated")
        );
    }

    /**
     * sqlcj never writes a manifest without an owner line before its first
     * entry, so a manifest that has none was edited and is reported instead of
     * read as owned by no configuration.
     */
    @Test
    void shouldReportAManifestWhoseOwnerLineNoLongerComesBeforeItsFirstEntry()
        throws IOException {
        Path outputDirectory = tempDir.resolve("generated");

        assertEquals(
            editedManifestDiagnostic(outputDirectory),
            readFailure(
                outputDirectory,
                NOTICE + "dev/example/generated/repositories/UsersRepository.java\n"
            )
        );

        assertEquals(
            editedManifestDiagnostic(outputDirectory),
            readFailure(
                outputDirectory,
                """
                    dev/example/generated/repositories/UsersRepository.java
                    # config: ../sqlcj.yaml
                    """
            )
        );

        assertEquals(editedManifestDiagnostic(outputDirectory), readFailure(outputDirectory, ""));

        assertEquals(editedManifestDiagnostic(outputDirectory), readFailure(outputDirectory, NOTICE));
    }

    /** The diagnostic of a manifest whose owner line was edited away. */
    private String editedManifestDiagnostic(Path outputDirectory) {
        return "Edited output manifest: %s: no '# config: ' line comes before its first entry; "
            .formatted(
                outputDirectory.resolve("dev/example/generated/sqlcj-manifest.txt")
            )
            + "restore it, or delete it together with the files it lists";
    }

    /** The message of reading one manifest's content back. */
    private String readFailure(Path outputDirectory, String content) throws IOException {
        writeManifest(outputDirectory, content);

        return assertThrows(
            IOException.class,
            () -> manifest.read(outputDirectory, "dev.example.generated")
        )
            .getMessage();
    }

    /** Writes the manifest of {@code dev.example.generated} by hand. */
    private void writeManifest(Path outputDirectory, String content) throws IOException {
        Path packageDirectory = outputDirectory.resolve("dev/example/generated");

        Files.createDirectories(packageDirectory);

        Files.writeString(packageDirectory.resolve("sqlcj-manifest.txt"), content);
    }

    /** What one run writes, the next run of the same package reads back. */
    @Test
    void shouldReadBackTheConfigurationAndEntriesItWrote() throws IOException {
        Path outputDirectory = tempDir.resolve("generated");

        manifest.write(
            outputDirectory,
            "dev.example.generated",
            manifest.configuration(outputDirectory, tempDir.resolve("sqlcj.yaml")),
            List.of(Path.of("dev", "example", "generated", "UsersRepository.java"))
        );

        assertEquals(
            Optional.of(
                new GeneratedOutputManifest.Contents(
                    "../sqlcj.yaml",
                    List.of("dev/example/generated/UsersRepository.java")
                )
            ),
            manifest.read(outputDirectory, "dev.example.generated")
        );
    }

    /**
     * The owning configuration is the configuration file relative to the output
     * directory, with {@code /} between its name elements, so the same file run
     * from another working directory names the same configuration.
     */
    @Test
    void shouldStateTheConfigurationRelativeToTheOutputDirectory() {
        Path outputDirectory = tempDir.resolve("target/generated-sources/sqlcj");

        assertEquals(
            "../../../sqlcj.yaml",
            manifest.configuration(outputDirectory, tempDir.resolve("sqlcj.yaml"))
        );

        assertEquals(
            "../../../config/sqlcj.yaml",
            manifest.configuration(
                outputDirectory,
                tempDir.resolve("config").resolve("sqlcj.yaml")
            )
        );

        assertEquals(
            "../../../sqlcj.yaml",
            manifest.configuration(
                outputDirectory,
                tempDir.resolve("config/../sqlcj.yaml")
            )
        );
    }

    @Test
    void shouldReportTheManifestItCannotRead() throws IOException {
        Path outputDirectory = tempDir.resolve("generated");
        Path manifestFile = outputDirectory
            .resolve("dev/example/generated")
            .resolve("sqlcj-manifest.txt");

        Files.createDirectories(manifestFile);

        IOException failure = assertThrows(
            IOException.class,
            () -> manifest.read(outputDirectory, "dev.example.generated")
        );

        assertEquals(
            "Cannot read output manifest: %s: Is a directory".formatted(manifestFile),
            failure.getMessage()
        );
    }

    @Test
    void shouldReportTheManifestItCannotWrite() throws IOException {
        Path outputDirectory = tempDir.resolve("generated");
        Path manifestFile = outputDirectory
            .resolve("dev/example/generated")
            .resolve("sqlcj-manifest.txt");

        Files.createDirectories(manifestFile);

        IOException failure = assertThrows(
            IOException.class,
            () -> manifest.write(
                outputDirectory,
                "dev.example.generated",
                "../sqlcj.yaml",
                List.of(Path.of("generated", "UsersRepository.java"))
            )
        );

        assertEquals(
            "Cannot write output manifest: %s: Is a directory".formatted(manifestFile),
            failure.getMessage()
        );
    }

    @Test
    void shouldDeleteOnlyAListedFileThisRunDidNotProduce() throws IOException {
        Path outputDirectory = tempDir.resolve("generated");

        Path produced = write(outputDirectory, "generated/UsersRepository.java");
        Path stale = write(outputDirectory, "generated/OrdersRepository.java");

        manifest.deleteStale(
            outputDirectory,
            List.of(
                "generated/UsersRepository.java",
                "generated/OrdersRepository.java"
            ),
            List.of(Path.of("generated", "UsersRepository.java"))
        );

        assertTrue(Files.exists(produced));
        assertFalse(Files.exists(stale));
    }

    @Test
    void shouldKeepAnUnlistedFile() throws IOException {
        Path outputDirectory = tempDir.resolve("generated");

        write(outputDirectory, "generated/UsersRepository.java");

        Path unlisted = write(outputDirectory, "generated/Helper.java");

        manifest.deleteStale(
            outputDirectory,
            List.of("generated/UsersRepository.java"),
            List.of(Path.of("generated", "UsersRepository.java"))
        );

        assertTrue(Files.exists(unlisted));
    }

    /**
     * An entry that escapes the output directory, is absolute, is not
     * normalized, is blank, names a directory, or names the same file this run
     * produced is never deleted.
     */
    @Test
    void shouldKeepAListedEntryItMustNotDelete() throws IOException {
        Path outputDirectory = tempDir.resolve("generated");

        Path produced = write(outputDirectory, "generated/UsersRepository.java");

        Path outside = tempDir.resolve("outside.java");

        Files.writeString(outside, "// outside\n");

        Path absolute = write(outputDirectory, "generated/AbsoluteRepository.java");
        Path notNormalized = write(outputDirectory, "generated/StaleRepository.java");
        Path directory = outputDirectory.resolve("generated/nested");

        Files.createDirectories(directory);

        Path hardLink = outputDirectory.resolve("generated/LinkedRepository.java");

        Files.createLink(hardLink, produced);

        manifest.deleteStale(
            outputDirectory,
            List.of(
                "../outside.java",
                absolute.toString(),
                "generated/./StaleRepository.java",
                "",
                "generated/nested",
                "generated/LinkedRepository.java"
            ),
            List.of(Path.of("generated", "UsersRepository.java"))
        );

        assertTrue(Files.exists(outside));
        assertTrue(Files.exists(absolute));
        assertTrue(Files.exists(notNormalized));
        assertTrue(Files.isDirectory(directory));
        assertTrue(Files.exists(hardLink));
        assertTrue(Files.exists(produced));
    }

    /**
     * A file sqlcj did not write is never deleted, so a listed file whose
     * generated-code notice a reader removed stays, without a diagnostic.
     */
    @Test
    void shouldKeepAListedFileWithoutTheGeneratedNotice() throws IOException {
        Path outputDirectory = tempDir.resolve("generated");

        Path takenOver = outputDirectory.resolve("generated/OrdersRepository.java");

        Files.createDirectories(takenOver.getParent());
        Files.writeString(takenOver, "// hand written now\n");

        manifest.deleteStale(
            outputDirectory,
            List.of("generated/OrdersRepository.java"),
            List.of()
        );

        assertEquals("// hand written now\n", Files.readString(takenOver));
    }

    /**
     * A listed file whose notice cannot be read is reported as the file it
     * could not read, not as a file it failed to delete.
     */
    @Test
    void shouldReportTheListedFileWhoseNoticeItCannotRead() throws IOException {
        Path outputDirectory = tempDir.resolve("generated");

        Path stale = write(outputDirectory, "generated/OrdersRepository.java");

        Files.setPosixFilePermissions(stale, PosixFilePermissions.fromString("-w-------"));

        try {
            assumeFalse(
                Files.isReadable(stale),
                "requires a filesystem that enforces file permissions"
            );

            IOException failure = assertThrows(
                IOException.class,
                () -> manifest.deleteStale(
                    outputDirectory,
                    List.of("generated/OrdersRepository.java"),
                    List.of()
                )
            );

            assertEquals(
                "Cannot read existing output file: %s: Permission denied".formatted(stale),
                failure.getMessage()
            );
        } finally {
            Files.setPosixFilePermissions(stale, PosixFilePermissions.fromString("rw-------"));
        }
    }

    /** One generated file, which carries the notice only sqlcj writes. */
    private Path write(Path outputDirectory, String entry) throws IOException {
        Path file = outputDirectory.resolve(entry);

        Files.createDirectories(file.getParent());

        Files.writeString(
            file,
            JavaCodeGenerator.GENERATED_NOTICE + "\n\n// " + entry + "\n"
        );

        return file;
    }
}
